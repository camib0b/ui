function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function collectVariableNames(value, names) {
  const text = JSON.stringify(value);
  for (const match of text.matchAll(/var\(--([a-z0-9-]+)\)/g)) {
    names.add(match[1]);
  }
}

function assertPreset(preset) {
  assert(preset.darkMode[0] === "class", "preset darkMode must be class");
  assert(preset.theme.container.padding === "2rem", "container padding must be 2rem");
  assert(preset.theme.container.center === true, "container must be centered");
  assert(preset.theme.container.screens["2xl"] === "1400px", "2xl screen must be 1400px");

  const { fontFamily, fontSize, colors, borderRadius, boxShadow, keyframes, animation } =
    preset.theme.extend;

  assert(fontFamily.sans[0] === "Roboto", "sans font must start with Roboto");
  assert(fontFamily.mono[0] === "ui-monospace", "mono font must match the site");
  assert(fontSize.base[0] === "0.95rem", "base font size must be 0.95rem");
  assert(fontSize["4xl"][0] === "2.25rem", "4xl font size must match the site");
  assert(borderRadius.lg === "var(--radius)", "large radius must use --radius");
  assert(borderRadius.md === "calc(var(--radius) - 2px)", "medium radius must match the site");
  assert(borderRadius.sm === "calc(var(--radius) - 4px)", "small radius must match the site");
  assert(boxShadow["elev-2"] === "var(--shadow-elev-2)", "missing elev-2 shadow");
  assert(boxShadow["elev-3"] === "var(--shadow-elev-3)", "missing elev-3 shadow");
  assert(colors.background.includes("--background"), "missing background color");
  assert(colors.primary.DEFAULT.includes("--primary"), "missing primary color");
  assert(colors.primary.foreground.includes("--primary-foreground"), "missing primary foreground");
  assert(colors.series.portfolio.includes("--series-portfolio"), "missing series.portfolio");
  assert(colors.series.benchmark.includes("--series-benchmark"), "missing series.benchmark");
  assert(colors["number-positive"].includes("--number-positive"), "missing number-positive");
  assert(colors["number-negative"].includes("--number-negative"), "missing number-negative");

  const requiredAnimations = {
    "analytics-rise": "analytics-rise",
    "portfolio-sync-sweep": "portfolio-sync-sweep",
    "portfolio-skeleton-pulse": "portfolio-skeleton-pulse",
    fadeUp: "fade-up",
    "contribution-flag": "contribution-flag",
    "curtain-fall": "curtain-fall",
  };
  for (const [keyframeName, animationName] of Object.entries(requiredAnimations)) {
    assert(keyframes[keyframeName], `preset is missing keyframes.${keyframeName}`);
    assert(animation[animationName], `preset is missing animation.${animationName}`);
    assert(
      animation[animationName].includes(keyframeName),
      `${animationName} must use the ${keyframeName} keyframe`
    );
  }

  const referencedVariables = new Set();
  collectVariableNames(colors, referencedVariables);
  collectVariableNames(borderRadius, referencedVariables);
  collectVariableNames(boxShadow, referencedVariables);
  collectVariableNames(keyframes, referencedVariables);
  collectVariableNames(animation, referencedVariables);

  for (const variableName of referencedVariables) {
    const definedOnRoot =
      Object.prototype.hasOwnProperty.call(lightVariables, variableName) ||
      variableName === "wave-offset" ||
      variableName === "contribution-column-duration";
    assert(definedOnRoot, `preset references --${variableName}, which ui.css does not define`);
  }
}

function assertStylesheet(stylesheet) {
  const requiredSnippets = [
    "--background: 0 0% 100%;",
    "--background: 220 14% 4%;",
    "--foreground: 220 14% 10%;",
    "--radius: 0.5rem;",
    '--font-body: "Roboto", sans-serif;',
    "family=Roboto",
    ".button",
    ".button-secondary",
    ".button-ghost",
    ".row",
    ".progress",
    ".progress-bar",
    "@keyframes fadeUp",
    "@keyframes analytics-rise",
    "prefers-reduced-motion",
    "border-radius: 0;",
  ];

  for (const snippet of requiredSnippets) {
    assert(stylesheet.includes(snippet), `ui.css is missing ${snippet}`);
  }

  assert(!stylesheet.includes("linear-gradient"), "ui.css must not add gradients");
  assert(!stylesheet.includes("border-radius: 999"), "ui.css must not add pills");
  assert(!stylesheet.includes("border-radius: 9999px"), "ui.css must not add pills");
}

function main() {
  const preset = require(path.join(packageRoot, "preset.js"));
  assertPreset(preset);

  const stylesheet = renderStylesheet(preset.theme.extend.keyframes);
  assertStylesheet(stylesheet);

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, stylesheet);
  process.stdout.write(`wrote ${path.relative(packageRoot, outputPath)}\n`);
}

main();
