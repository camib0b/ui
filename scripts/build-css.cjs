function renderCustomProperties(variables, includeComments) {
  const lines = [];
  for (const [name, value] of Object.entries(variables)) {
    if (includeComments && commentBefore[name]) {
      lines.push("");
      lines.push(commentBefore[name]);
    }
    lines.push(`  --${name}: ${value};`);
  }
  return lines.join("\n");
}

function cssPropertyName(propertyName) {
  return propertyName.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function renderKeyframes(keyframes) {
  return Object.entries(keyframes)
    .map(([name, frames]) => {
      const body = Object.entries(frames)
        .map(([stop, declarations]) => {
          const rules = Object.entries(declarations)
            .map(
              ([propertyName, propertyValue]) =>
                `    ${cssPropertyName(propertyName)}: ${propertyValue};`
            )
            .join("\n");
          return `  ${stop} {\n${rules}\n  }`;
        })
        .join("\n");
      return `@keyframes ${name} {\n${body}\n}`;
    })
    .join("\n\n");
}

